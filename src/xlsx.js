const zlib = require('zlib');

const esc = (s) => String(s).replace(/[<>&"']/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[c]))
  // إزالة محارف التحكم غير المسموحة في XML
  .replace(/[\x00-\x08\x0B\x0C\x0E-\x1F]/g, '');

function colName(i) {
  let s = '';
  for (i += 1; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s;
  return s;
}

// rows: مصفوفة صفوف؛ كل صف إما مصفوفة قيم أو {cells:[], style:'title'|'header'|'note'}
function sheetXml(rows, widths) {
  const styleId = { title: 2, header: 1, note: 3 };
  let xml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
    '<sheetViews><sheetView rightToLeft="1" workbookViewId="0"/></sheetViews>' +
    '<sheetFormatPr defaultRowHeight="18"/>';
  if (widths && widths.length) {
    xml += '<cols>' + widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('') + '</cols>';
  }
  xml += '<sheetData>';
  rows.forEach((row, r) => {
    const cells = Array.isArray(row) ? row : row.cells;
    const s = Array.isArray(row) ? 0 : styleId[row.style] || 0;
    xml += `<row r="${r + 1}">`;
    cells.forEach((v, c) => {
      if (v === null || v === undefined || v === '') return;
      const ref = colName(c) + (r + 1);
      const sa = s ? ` s="${s}"` : '';
      if (typeof v === 'number' && Number.isFinite(v)) xml += `<c r="${ref}"${sa}><v>${v}</v></c>`;
      else xml += `<c r="${ref}"${sa} t="inlineStr"><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
    });
    xml += '</row>';
  });
  return xml + '</sheetData></worksheet>';
}

